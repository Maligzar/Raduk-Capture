#!/usr/bin/env python3
"""Phase 155.2: the register of constants never checked against the sky.

A constant that was tuned on synthetic frames, derived without measurement,
or taken from a datasheet carries a comment on the line above it:

    // UNVERIFIED(item N): what would verify it

where N is an item of docs/CLEAR-NIGHT-CHECKLIST.md. This script collects
every tag under src/ and writes docs/UNVERIFIED.md, one table grouped by
checklist item.

    python tools/unverified_report.py           write docs/UNVERIFIED.md
    python tools/unverified_report.py --check   fail (exit 1) if a tag is
        malformed, names an item the checklist does not have, or the
        committed register differs from what would be written now

Standard library only, and no network: it runs in CI and offline alike.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
CHECKLIST = ROOT / "docs" / "CLEAR-NIGHT-CHECKLIST.md"
REGISTER = ROOT / "docs" / "UNVERIFIED.md"

TAG = re.compile(r"//\s*UNVERIFIED\(item (\d+)\):\s*(\S.*?)\s*$")
LOOSE = re.compile(r"UNVERIFIED\s*\(")          # anything that tries to be a tag
HEADING = re.compile(r"^## (\d+)\.\s+(.*)$")     # items 1 to 19
NUMBERED = re.compile(r"^(\d+)\.\s+\*\*(.+?)\*\*")  # items 20 and up
DECL = re.compile(r"([A-Za-z_][A-Za-z0-9_]*)\s*(?:\[[^\]]*\])?\s*=\s*([^;]+);")


def checklist_items(text):
    """Item number -> title. Numbered sub-steps inside items 1 to 19 reuse
    small numbers, so a numbered line counts only from 20 up."""
    items = {}
    for line in text.splitlines():
        m = HEADING.match(line)
        if m:
            items[int(m.group(1))] = clean_title(m.group(2))
            continue
        m = NUMBERED.match(line)
        if m and int(m.group(1)) >= 20:
            items.setdefault(int(m.group(1)), clean_title(m.group(2)))
    return items


def clean_title(t):
    t = t.replace("`", "").replace("**", "")
    t = re.split(r"\s+[—-]{1,2}\s+", t)[0]  # drop " — subtitle"
    return t.strip().rstrip(".")


def describe(line):
    """The constant's name and value from its declaration line, or the
    line itself when it is not a plain assignment."""
    code = line.split("//", 1)[0].strip()
    fn = re.search(r"([A-Za-z_][A-Za-z0-9_]*)\s*\(\)\s*const\s*\{", code)
    if fn:
        return fn.group(1) + "()", ""
    if code.count(";") > 1:
        return code, ""
    m = DECL.search(code)
    if m and not code.startswith(("if", "return")):
        return m.group(1), m.group(2).strip()
    return code, ""


def collect():
    tags, errors = [], []
    for path in sorted(SRC.rglob("*")):
        if path.suffix not in (".h", ".cpp", ".hpp"):
            continue
        rel = path.relative_to(ROOT).as_posix()
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
        for i, line in enumerate(lines):
            if not LOOSE.search(line):
                continue
            m = TAG.search(line)
            if not m:
                errors.append(f"{rel}:{i + 1}: malformed tag (want '// UNVERIFIED(item N): text'): {line.strip()}")
                continue
            j = i + 1
            while j < len(lines) and (not lines[j].strip() or lines[j].strip().startswith("//")):
                j += 1
            if j >= len(lines):
                errors.append(f"{rel}:{i + 1}: tag with no code after it")
                continue
            name, value = describe(lines[j])
            tags.append({"item": int(m.group(1)), "why": m.group(2), "file": rel,
                         "line": j + 1, "name": name, "value": value})
    return tags, errors


def cell(s):
    return s.replace("|", "\\|")


def render(tags, items):
    out = [
        "# Constants never checked against the sky",
        "",
        "Generated by `tools/unverified_report.py` from the `UNVERIFIED(item N)` tags in `src/`. "
        "Do not edit by hand: tag the constant, then run the script. CI fails when this file is stale "
        "or a tag names an item [`CLEAR-NIGHT-CHECKLIST.md`](CLEAR-NIGHT-CHECKLIST.md) does not have.",
        "",
        "Line numbers are left out on purpose, so an edit elsewhere in a file does not make this register stale; "
        "search the file for `UNVERIFIED(item`.",
        "",
        "A tag is removed when its clear-night item has been run and the value confirmed or replaced, "
        "with the night noted in the checklist.",
        "",
        f"{len(tags)} constants across {len({t['item'] for t in tags})} checklist items.",
    ]
    for item in sorted({t["item"] for t in tags}):
        out += ["", f"## Item {item}: {items.get(item, '?')}", "",
                "| Constant | Value | File | What verifies it |", "|---|---|---|---|"]
        for t in sorted((t for t in tags if t["item"] == item), key=lambda t: (t["file"], t["line"])):
            value = f"`{cell(t['value'])}`" if t["value"] else ""
            out.append(f"| `{cell(t['name'])}` | {value} | `{t['file']}` | {cell(t['why'])} |")
    return "\n".join(out) + "\n"


def main(argv):
    check = "--check" in argv
    items = checklist_items(CHECKLIST.read_text(encoding="utf-8"))
    tags, errors = collect()
    for t in tags:
        if t["item"] not in items:
            errors.append(f"{t['file']}:{t['line']}: item {t['item']} is not in CLEAR-NIGHT-CHECKLIST.md")
    text = render(tags, items)
    if check:
        current = REGISTER.read_text(encoding="utf-8").replace("\r\n", "\n") if REGISTER.exists() else ""
        if current != text:
            errors.append("docs/UNVERIFIED.md is stale: run python tools/unverified_report.py and commit it")
        for e in errors:
            print(e)
        print(f"{len(tags)} UNVERIFIED tags, {len(errors)} problems")
        return 1 if errors else 0
    for e in errors:
        print(e)
    if errors:
        return 1
    REGISTER.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {REGISTER.relative_to(ROOT).as_posix()}: {len(tags)} constants")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
